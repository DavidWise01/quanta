import assert from "node:assert/strict";
import {PHASE_II_FREEZE,genesis,advance} from "./ada-201n-generational-engine.mjs";
import {PHASE_III_FREEZE} from "./ada-211n-epoch-engine.mjs";
import {commitEpochJournal,EPOCH_ENTRY_KEY} from "./ada-212n-epoch-journal.mjs";
import {proveEpoch,verifyEpochProof,inspectPersistedEpoch,PROVENANCE_SCHEMA} from "./ada-213n-epoch-provenance.mjs";
const chain=advance([genesis()],240),prior=JSON.stringify(chain);
const proof=proveEpoch(chain,10,{maxAncestors:5});
assert.equal(proof.schema,PROVENANCE_SCHEMA);
assert.equal(proof.phaseIIIFreeze,PHASE_III_FREEZE);
assert.equal(proof.originalSourceRoot,PHASE_II_FREEZE);
assert.equal(proof.independentSourceRoots,1);
assert.equal(proof.selectedState,"OPEN_TAIL");
assert.equal(proof.sealedReceipt,false);
assert.equal(proof.generations.length,1);
assert.equal(proof.generations[0].n,240);
assert.equal(proof.returnedAncestors,5);
assert.equal(proof.truncated,true);
assert.equal(proof.completeAncestryDepth,11);
assert(verifyEpochProof(chain,proof).pass);
assert.deepEqual(proveEpoch(chain,10,{maxAncestors:5}),proof,"Bit-identical replay");
const sealed=proveEpoch(chain,9,{maxAncestors:24});
assert.equal(sealed.sealedReceipt,true);
assert.equal(sealed.generations.length,24);
assert.equal(sealed.generations[0].n,216);
assert.equal(sealed.generations.at(-1).n,239);
assert.equal(sealed.ancestors[0].sealedStorageKey,EPOCH_ENTRY_KEY(9));
assert.equal(sealed.firstInheritedParent,chain[215].hash);
assert(verifyEpochProof(chain,sealed).pass);
const altered=structuredClone(proof);altered.generations[0].hash="0000000000000000";
assert.equal(verifyEpochProof(chain,altered).pass,false);
const restitched=structuredClone(sealed);restitched.fingerprint="0".repeat(16);
assert.equal(verifyEpochProof(chain,restitched).pass,false);
const genesisProof=proveEpoch([genesis()],0);
assert.equal(genesisProof.completeAncestryDepth,1);
assert.equal(genesisProof.sourceStart,0);
assert.throws(()=>proveEpoch(chain,11),/outside source lineage/);
assert.throws(()=>proveEpoch(chain,1,{maxAncestors:257}),/Ancestor limit/);
const map=new Map(),store={getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,String(v))};
commitEpochJournal(store,chain);
const stored=inspectPersistedEpoch(store,9);
assert.equal(stored.verified,true);
assert.equal(stored.sealedReceiptPresent,true);
assert.equal(stored.pendingSealed,0);
const tail=inspectPersistedEpoch(store,10);
assert.equal(tail.sealedReceiptPresent,false);
assert.equal(store.getItem(EPOCH_ENTRY_KEY(10)),null);
assert.equal(JSON.stringify(chain),prior,"Original ancestry unchanged");
const corrupt=JSON.parse(store.getItem(EPOCH_ENTRY_KEY(9)));corrupt.holds+=1;
store.setItem(EPOCH_ENTRY_KEY(9),JSON.stringify(corrupt));
assert.throws(()=>inspectPersistedEpoch(store,9),/Sealed epoch divergence/);
