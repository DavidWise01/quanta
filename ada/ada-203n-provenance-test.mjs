assert.equal(proof.ancestors[0].n,64);
assert.equal(proof.ancestors[0].storageKey,ENTRY_KEY(64));
assert(validateProvenance(proof,chain).pass);
assert.deepEqual(traceLineage(chain,64,13),proof,"Replay must be deterministic");
