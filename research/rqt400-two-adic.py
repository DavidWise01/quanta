#!/usr/bin/env python3
"""RQT-400: exact two-adic branch enumeration in RQT-388 reduced kernel.
Input FULL JSON generated by rqt388-exact-second-key.py --out.
Not the small published RQT-388 summary.
"""
import argparse,itertools,json
from pathlib import Path

def norm(Q,v):
 return 2+sum(Q[i][j]*v[i]*v[j] for i in range(3) for j in range(3))

def audit(Q,max_power=6,max_nodes=1000000):
 assert len(Q)==3 and all(len(row)==3 for row in Q)
 assert all(Q[i][j]==Q[j][i] for i in range(3) for j in range(3))
 assert 1<=max_power<=30
 residues=[(0,0,0)];mod=1;levels=[]
 for k in range(1,max_power+1):
  new_mod=2*mod
  if len(residues)*8>max_nodes:
   levels.append({'power':k,'status':'SKIPPED_NODE_CAP','parent_count':len(residues)})
   break
  survivors=[];alive=dead=0
  for v in residues:
   # For any integer t, N(v+mod*t) = N(v) (mod 2*mod),
   # since mod=2^(k-1) and mod^2 divisible by 2*mod
   # when mod>=2; at mod=1 this identity is NOT valid!
   if mod>=2:
    if norm(Q,v)%new_mod:
     dead+=1;continue
    alive+=1
    survivors.extend(tuple(v[i]+mod*t[i] for i in range(3))
                    for t in itertools.product((0,1),repeat=3))
   else:
    for t in itertools.product((0,1),repeat=3):
     if norm(Q,t)%2==0:survivors.append(t)
  if mod>=2: assert len(survivors)==8*alive
  levels.append({'power':k,'modulus':new_mod,'survivors':len(survivors),
                 'all_eight_parent_branches':alive if mod>=2 else None,
                 'dead_parent_branches':dead if mod>=2 else None})
  residues=survivors;mod=new_mod
  if not residues:break
 return {'RQT':400,'status':'EXACT FINITE 2-ADIC TEST',
         'levels':levels,'obstruction_found':bool(levels and levels[-1].get('survivors')==0),
         'target_root19':'OPEN unless valid target-Q yields zero surviving level',
         'scope':'Finite 2-adic levels; survival does not prove integral root existence'}

if __name__=='__main__':
 p=argparse.ArgumentParser()
 p.add_argument('full_kernel_json')
 p.add_argument('--max-power',type=int,default=6)
 p.add_argument('--max-nodes',type=int,default=1000000)
 p.add_argument('--out')
 a=p.parse_args()
 src=json.loads(Path(a.full_kernel_json).read_text())
 raw=src.get('restricted_F4_Gram',src.get('restricted_Gram'))
 if raw is None:raise ValueError('Full reduced Gram required, not RQT-388 summary')
 result=audit([[int(v) for v in row] for row in raw],a.max_power,a.max_nodes)
 if a.out:Path(a.out).write_text(json.dumps(result,indent=2)+'\n')
 print(json.dumps(result,indent=2))
