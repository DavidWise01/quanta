import assert from "node:assert/strict";
import {genesis,advance} from "./ada-201n-generational-engine.mjs";
import {appendJournal,HEAD_KEY as SOURCE_HEAD} from "./ada-202n-generation-archive.mjs";
import {EPOCH_HEAD_KEY,EPOCH_ENTRY_KEY,commitEpochJournal,restoreEpochJournal} from "./ada-212n-epoch-journal.mjs";
const fresh=()=>{const map=new Map();return {map,getItem:k=>map.has(k)?map.get(k):null,setItem:(k,v)=>map.set(k,String(v)),removeItem:k=>map.delete(k)}};
const storage=fresh(),root=[genesis()];
let state=commitEpochJournal(storage,root);
assert.equal(state.sealedCount,0);assert.equal(state.openTail,true);
assert.equal(storage.getItem(EPOCH_ENTRY_KEY(0)),null,"Never store OPEN_TAIL");
let chain=advance(root,23),snapshot=commitEpochJournal(storage,chain);
assert.equal(snapshot.sealedCount,1);assert.equal(snapshot.openTail,false);
assert.equal(JSON.parse(storage.getItem(EPOCH_ENTRY_KEY(0))).state,"SEALED");
const first=storage.getItem(EPOCH_ENTRY_KEY(0));
chain=advance(chain,1);snapshot=commitEpochJournal(storage,chain);
assert.equal(snapshot.sealedCount,1);assert.equal(snapshot.openTail,true);
assert.equal(storage.getItem(EPOCH_ENTRY_KEY(1)),null,"OPEN_TAIL remains unrecorded");
assert.equal(storage.getItem(EPOCH_ENTRY_KEY(0)),first,"Sealed epoch never rewritten");
chain=advance(chain,216);snapshot=commitEpochJournal(storage,chain);
assert.equal(chain.length,241);
assert.equal(snapshot.sealedCount,10);
assert.equal(snapshot.openTail,true);
assert.equal(storage.getItem(EPOCH_ENTRY_KEY(10)),null);
assert.equal(restoreEpochJournal(storage).chain.length,241);
const repeated=commitEpochJournal(storage,chain);
assert.equal(repeated.sealedCount,10,"Idempotent commit");
assert.equal(storage.getItem(EPOCH_ENTRY_KEY(0)),first);
const corrupt=fresh();commitEpochJournal(corrupt,chain);
const altered=JSON.parse(corrupt.getItem(EPOCH_ENTRY_KEY(2)));altered.holds+=1;
corrupt.setItem(EPOCH_ENTRY_KEY(2),JSON.stringify(altered));
assert.throws(()=>restoreEpochJournal(corrupt),/Sealed epoch divergence/);
const orphan=fresh();orphan.setItem(EPOCH_ENTRY_KEY(0),first);
assert.throws(()=>restoreEpochJournal(orphan),/Orphan sealed epoch/);
const partial=fresh();commitEpochJournal(partial,advance(root,23));
const child=advance(root,47);
appendJournal(partial,child); // interrupted between source-commit and epoch-commit
assert.equal(restoreEpochJournal(partial).pending,1);
const healed=commitEpochJournal(partial,child);assert.equal(healed.sealedCount,2);
const uncommitted=fresh();commitEpochJournal(uncommitted,chain);
uncommitted.setItem(EPOCH_ENTRY_KEY(10),JSON.stringify({bogus:true}));
assert.throws(()=>restoreEpochJournal(uncommitted),/Uncommitted sealed epoch/);
const wrongRoot=fresh();commitEpochJournal(wrongRoot,root);
const badHead=JSON.parse(wrongRoot.getItem(EPOCH_HEAD_KEY));badHead.phaseIIIFreeze="0".repeat(40);
wrongRoot.setItem(EPOCH_HEAD_KEY,JSON.stringify(badHead));
assert.throws(()=>restoreEpochJournal(wrongRoot),/Invalid Phase IV head/);
const sourceCorrupt=fresh();commitEpochJournal(sourceCorrupt,chain);
const raw=JSON.parse(sourceCorrupt.getItem(SOURCE_HEAD));raw.tip="0".repeat(16);
sourceCorrupt.setItem(SOURCE_HEAD,JSON.stringify(raw));
assert.throws(()=>restoreEpochJournal(sourceCorrupt),/Journal tip mismatch/);
